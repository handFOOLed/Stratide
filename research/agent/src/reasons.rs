#[cfg(test)]
mod tests {
    use super::text;

    #[test]
    fn real_install_and_frontend_codes_have_chinese_text() {
        assert_eq!(
            text("LATE_OR_FUTURE_CATALOG_NOT_DECISION_EVIDENCE"),
            Some("行情目录为晚到或回填数据，不能作为当日研究依据")
        );
        assert_eq!(
            text("MARKET_RESEARCH_LOCAL_FAILURE"),
            Some("本地研究阶段出现异常，研究已安全停止")
        );
        assert_eq!(text("DAILY_BUDGET_EXHAUSTED"), Some("今日研究预算已用完"));
        assert_eq!(text("AUTHORIZATION_REQUIRED"), Some("研究模型尚未获得授权"));
        assert_eq!(text("OWNER_INVOICE:2026-11"), Some("账单已人工核对"));
    }

    #[test]
    fn unknown_codes_are_not_invented() {
        assert_eq!(text("FUTURE_UNMAPPED_CODE"), None);
        assert_eq!(text(""), None);
        assert_eq!(text("authorized"), None);
    }
}
